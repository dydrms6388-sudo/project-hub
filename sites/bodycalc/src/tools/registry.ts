export const toolBySlug = (slug: string): ToolMeta | undefined =>
  tools.find((t) => t.slug === slug);

const CATEGORY_ORDER = [CAT_BODY, CAT_ENERGY, CAT_SLEEP, CAT_EXERCISE, CAT_DATE];

export const toolsByCategory = (): { category: string; items: ToolMeta[] }[] => {
  const map = new Map<string, ToolMeta[]>();
  for (const t of tools) {
    const arr = map.get(t.category) ?? [];
    arr.push(t);
    map.set(t.category, arr);
  }
  return CATEGORY_ORDER.filter((c) => map.has(c)).map((category) => ({
    category,
    items: map.get(category)!,
  }));
};
